export const LANGUAGES = {
    en: { label: 'English', flag: '🇬🇧', isRTL: false },
    ur: { label: 'Urdu', flag: '🇵🇰', isRTL: true },
};

export const translations = { en, ur };

// Safe lookup — falls back from ur → en → key string
export const translate = (lang, path) => {
    const segments = Array.isArray(path) ? path : String(path).split('.');
    const lookup = (src) => segments.reduce((acc, seg) => (acc && typeof acc === 'object' ? acc[seg] : undefined), src);
    const primary = lookup(translations[lang]);
    if (typeof primary === 'string') return primary;
    const fallback = lookup(translations.en);
    if (typeof fallback === 'string') return fallback;
    return segments.join('.');
};
